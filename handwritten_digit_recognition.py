###This project uses a Convolutional Neural Network (CNN) to recognize handwritten digits from the MNIST dataset.

import numpy as np
import matplotlib.pyplot as plt

import tensorflow as tf
from tensorflow.keras import layers, models

from sklearn.metrics import confusion_matrix, classification_report

(X_train, y_train), (X_test, y_test) = tf.keras.datasets.mnist.load_data()

print("Training images:", X_train.shape)
print("Training labels:", y_train.shape)
print("Testing images:", X_test.shape)
print("Testing labels:", y_test.shape)

plt.figure(figsize=(10, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_train[i], cmap="gray")
    plt.title(f"Label: {y_train[i]}")
    plt.axis("off")

plt.tight_layout()
plt.show()

X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

X_train = X_train.reshape(-1, 28, 28, 1)
X_test = X_test.reshape(-1, 28, 28, 1)

print("Training shape:", X_train.shape)
print("Testing shape:", X_test.shape)

model = models.Sequential([
    layers.Conv2D(32, (3, 3), activation="relu", input_shape=(28, 28, 1)),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(64, (3, 3), activation="relu"),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),

    layers.Dense(64, activation="relu"),
    layers.Dense(10, activation="softmax")
])

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

history = model.fit(
    X_train,
    y_train,
    epochs=5,
    validation_split=0.1
)

test_loss, test_accuracy = model.evaluate(X_test, y_test)

print("Test Accuracy:", test_accuracy)
print("Test Accuracy Percentage:", test_accuracy * 100, "%")

predictions = model.predict(X_test)

predicted_labels = np.argmax(predictions, axis=1)

print("Predicted:", predicted_labels[:10])
print("Actual:   ", y_test[:10])

plt.imshow(X_test[0].reshape(28, 28), cmap="gray")

plt.title(f"Predicted: {predicted_labels[0]}")
plt.axis("off")

plt.show()

cm = confusion_matrix(y_test, predicted_labels)

plt.figure(figsize=(8, 6))
plt.imshow(cm)

plt.title("MNIST Confusion Matrix")
plt.xlabel("Predicted Label")
plt.ylabel("Actual Label")

plt.xticks(range(10))
plt.yticks(range(10))

plt.colorbar()

plt.show()

print(
    classification_report(
        y_test,
        predicted_labels,
        digits=4
    )
)

plt.figure(figsize=(10, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(X_test[i].reshape(28, 28), cmap="gray")
    plt.title(
        f"Pred: {predicted_labels[i]}\nActual: {y_test[i]}"
    )
    plt.axis("off")

plt.tight_layout()
plt.show()

model.save("mnist_digit_recognition_model.keras")